"""Build a Kaggle GPU job from an experiment file and (optionally) push it.

The job is self-contained: run.py embeds a tarball of this repo's code (src/, envs/, kaggle/job.sh) and one resolved
config per arm, so changing a knob needs no commit: edit or override, then push. openpi itself is cloned on Kaggle at
the commit pinned in envs/openpi.txt and never modified.

Usage:
  python kaggle/push.py experiments/j2_steps.yaml --push
  python kaggle/push.py experiments/j2_steps.yaml --name j2b --set policy.noise=episode --push    # all arms
  python kaggle/push.py experiments/j2_steps.yaml --set steps1.policy.num_steps=2                  # one arm
  python kaggle/push.py experiments/verify_replay.yaml --push    # mode: replay, attaches the experiment's dataset
Then: kaggle kernels status <user>/<prefix><name>; python kaggle/fetch.py <name>   (-> runs/<name>/)
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import os
import subprocess
import sys
import tarfile

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from vlalab.config import resolve_experiment  # noqa: E402

KERNEL_PREFIX = "vlalab-"
SHIPPED = ["src", "envs", "kaggle/job.sh"]

RUN_PY = '''\
"""Generated by kaggle/push.py from {experiment} (job {name}). Unpacks the vlalab code and runs kaggle/job.sh."""
import base64, io, json, os, subprocess, tarfile
CODE = {code!r}
ARMS = {arms!r}
ENV = {env!r}
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE))).extractall("/tmp/vlalab")
os.makedirs("/tmp/arms", exist_ok=True)
for i, arm in enumerate(ARMS):
    json.dump(arm, open(f"/tmp/arms/arm{{i}}.json", "w"), indent=2)
print("job", {name!r}, "| arms:", [a["name"] for a in ARMS], "|", ENV, flush=True)
subprocess.run(["bash", "/tmp/vlalab/kaggle/job.sh"], check=True,
               env={{**os.environ, **ENV, "VLALAB": "/tmp/vlalab", "ARMS_DIR": "/tmp/arms", "N_ARMS": str(len(ARMS))}})
'''


def code_tarball() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in SHIPPED:
            tar.add(os.path.join(ROOT, rel), arcname=rel,
                    filter=lambda t: None if "__pycache__" in t.name or t.name.endswith(".pyc") else t)
    return base64.b64encode(buf.getvalue()).decode()


def openpi_pin() -> tuple[str, str]:
    lines = [l.split() for l in open(os.path.join(ROOT, "envs", "openpi.txt")) if l.strip() and not l.startswith("#")]
    return lines[0][0], lines[0][1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("experiment", help="experiments/<file>.yaml")
    ap.add_argument("--name", help="job name (default: experiment file stem); kernel = <user>/" + KERNEL_PREFIX + "<name>")
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                    help="override, e.g. policy.num_steps=3 (all arms) or steps1.eval.trials=1 (one arm)")
    ap.add_argument("--push", action="store_true")
    args = ap.parse_args()

    spec = yaml.safe_load(open(args.experiment))
    name = args.name or os.path.splitext(os.path.basename(args.experiment))[0]
    mode = spec.get("mode", "eval")
    arms = [a.to_dict() for a in resolve_experiment(spec, args.set)]
    repo, sha = openpi_pin()
    env = {"MODE": mode, "OPENPI_REPO": repo, "OPENPI_SHA": sha}
    print(json.dumps({"name": name, "mode": mode, "env": env, "arms": arms}, indent=1))

    user = json.load(open(os.path.expanduser("~/.kaggle/kaggle.json")))["username"]
    job = os.path.join(ROOT, "kaggle", "build", name)
    os.makedirs(job, exist_ok=True)
    with open(os.path.join(job, "run.py"), "w", newline="\n") as f:
        f.write(RUN_PY.format(experiment=os.path.relpath(args.experiment, ROOT).replace("\\", "/"), name=name,
                              code=code_tarball(), arms=arms, env=env))
    meta = {
        "id": f"{user}/{KERNEL_PREFIX}{name}", "title": f"{KERNEL_PREFIX}{name}", "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_internet": True, "dataset_sources": [d.format(user=user) for d in spec.get("datasets", [])], "competition_sources": [],
        "kernel_sources": [],
    }
    json.dump(meta, open(os.path.join(job, "kernel-metadata.json"), "w"), indent=2)
    print("job written:", job)
    if args.push:
        subprocess.check_call(["kaggle", "kernels", "push", "-p", job])


if __name__ == "__main__":
    main()
